class PixelFont:
    """Renders (and caches) crisp pixel text surfaces."""

    ADVANCE = 6

    def __init__(self):
        self._cache = {}

    def width(self, text, scale=1):
        return max(0, (self.ADVANCE * len(text) - 1)) * scale

    def _raw(self, text, color, scale):
        text = text.upper()
        w = max(1, self.ADVANCE * len(text) - 1)
        base = pygame.Surface((w, 7), pygame.SRCALPHA)
        for i, ch in enumerate(text):
            cols = _H.get(ch, _H["?"])
            for cx, bits in enumerate(cols):
                for r in range(7):
                    if (bits >> r) & 1:
                        base.set_at((i * self.ADVANCE + cx, r), color)
        if scale > 1:
            base = pygame.transform.scale(base, (w * scale, 7 * scale))
        return base

    def render(self, text, color, scale=1, shadow=None):
        key = (text, tuple(color), scale, tuple(shadow) if shadow else None)
        img = self._cache.get(key)
        if img is None:
            if len(self._cache) > 700:
                self._cache.clear()
            main = self._raw(text, color, scale)
            if shadow:
                w, h = main.get_size()
                img = pygame.Surface((w + scale, h + scale), pygame.SRCALPHA)
                img.blit(self._raw(text, shadow, scale), (scale, scale))
                img.blit(main, (0, 0))
            else:
                img = main
            self._cache[key] = img
        return img

    def draw(self, surf, text, pos, color, scale=1, shadow=None, anchor="topleft"):
        img = self.render(text, color, scale, shadow)
        rect = img.get_rect()
        setattr(rect, anchor, (int(pos[0]), int(pos[1])))
        surf.blit(img, rect)
        return rect
